func TestPassfileLineEscapesColonsAndBackslashes(t *testing.T) {
	if got, want := PassfileLine(`a:b\c`), `*:*:*:replicator:a\:b\\c`+"\n"; got != want {
		t.Errorf("PassfileLine = %q, want %q", got, want)
	}
}

func TestPassfilePathIsInTheReplicasRuntimeDirectory(t *testing.T) {
	if got, want := PassfilePath("default-pg-0"), "/run/expanse-block/default-pg-0/pgpass"; got != want {
		t.Errorf("PassfilePath = %q, want %q", got, want)
	}
}

func TestReplicationNamesThePassfileNotThePassword(t *testing.T) {
	got := Replication("192.168.1.9", 5432, "/mnt/my vol/.expanse-postgres/pgpass")
	want := `host=192.168.1.9 port=5432 user=replicator passfile='/mnt/my vol/.expanse-postgres/pgpass' application_name=expanse`
	if got != want {
		t.Errorf("Replication = %q, want %q", got, want)
	}
}

func TestScrubSwapsThePasswordForThePassfile(t *testing.T) {
	const pf = "/m/.expanse-postgres/pgpass"
	for in, want := range map[string]string{
		// pg_basebackup -R's shape: every value quoted.
		`user=replicator password='s3 cr\'et' channel_binding=prefer host=10.0.0.2 port=5432`: `user=replicator channel_binding=prefer host=10.0.0.2 port=5432 passfile=` + pf,
		// pgReconfigure's 1.12 shape: unquoted.
		`host=10.0.0.3 port=5432 user=replicator password=s3cret application_name=expanse`: `host=10.0.0.3 port=5432 user=replicator application_name=expanse passfile=` + pf,
	} {
		got, changed := Scrub(in, pf)
		if got != want || !changed {
			t.Errorf("Scrub(%q) = %q, %v; want %q, true", in, got, changed, want)
		}
	}
	if got, changed := Scrub("host=10.0.0.3 user=replicator", pf); got != "host=10.0.0.3 user=replicator passfile="+pf || !changed {
		t.Errorf("Scrub without a passfile = %q, %v; want it named", got, changed)
	}
	// 1.12.3 put the passfile on the volume; a start moves it to the runtime directory.
	if got, changed := Scrub("host=10.0.0.3 passfile=/m/old/pgpass user=replicator", pf); got != "host=10.0.0.3 passfile="+pf+" user=replicator" || !changed {
		t.Errorf("Scrub with an old passfile = %q, %v; want the new one named", got, changed)
	}
	clean := `host=10.0.0.3 port=5432 user=replicator passfile=` + pf
	if got, changed := Scrub(clean, pf); got != clean || changed {
		t.Errorf("Scrub(clean) = %q, %v; want it unchanged", got, changed)
	}
}

func TestScrubAutoConfRewritesOnlyPrimaryConninfo(t *testing.T) {
	const pf = "/m/.expanse-postgres/pgpass"
	in := "# Do not edit this file manually!\n" +
		// The conninfo password='s3\'cr\\et', with ' and \ doubled as postgres writes auto.conf.
		`primary_conninfo = 'user=replicator password=''s3\\''cr\\\\et'' host=10.0.0.2 port=5432'` + "\n" +
		"primary_slot_name = 'expanse_default_pg_1'\n"
	got, changed := ScrubAutoConf(in, pf)
	if !changed || strings.Contains(got, "s3") || strings.Contains(got, "password") {
		t.Fatalf("ScrubAutoConf left the password: %q", got)
	}
	want := "primary_conninfo = 'user=replicator host=10.0.0.2 port=5432 passfile=" + pf + "'\n"
	if !strings.Contains(got, want) || !strings.Contains(got, "primary_slot_name = 'expanse_default_pg_1'\n") {
		t.Errorf("ScrubAutoConf = %q, want a line %q and the slot line kept", got, want)
	}
	if again, changed := ScrubAutoConf(got, pf); changed || again != got {
		t.Errorf("a scrubbed file changed again: %q", again)
	}
}
